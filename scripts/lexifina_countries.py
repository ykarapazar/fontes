"""Write src/world_legal_mcp/jurisdictions/_lexifina_data.py: the countries Fontes reads only
through Lexifina's global law record (src/world_legal_mcp/lexifina.py).

    uv run python scripts/lexifina_countries.py

A country is listed when Lexifina's hosted server holds law text for it and no Fontes adapter
has its ISO code (India's adapter reads its legislation from here, so India is listed too). Rerun after Lexifina adds a country or Fontes adds an adapter.
"""
from __future__ import annotations

import json
import pprint
import re
import urllib.request
from collections import defaultdict
from pathlib import Path

from world_legal_mcp import lexifina, registry

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/world_legal_mcp/jurisdictions/_lexifina_data.py"
MANIFEST = "https://raw.githubusercontent.com/lexifina/global-law/main/manifest.json"
UA = {"User-Agent": "fontes-mcp (+https://github.com/ykarapazar/fontes)", "Content-Type": "application/json"}


def _get(url: str, body: dict | None = None) -> dict:
    req = urllib.request.Request(url, data=json.dumps(body).encode() if body else None, headers=UA)
    return json.load(urllib.request.urlopen(req, timeout=120))


def main() -> None:
    corpora = _get(MANIFEST)["corpora"]
    served = _get(lexifina.URL, {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                                 "params": {"name": "list_jurisdictions", "arguments": {}}})
    with_text = {c["country"] for c in served["result"]["structuredContent"]["countries"] if c["with_text"]}
    registry.discover()
    # an adapter that reads only its legislation from Lexifina (India) is still listed here: it supplies the data
    live = {c for c, j in registry._all.items()
            if not getattr(j, "via_lexifina", False) and not getattr(j, "lexifina_legislation", False)}
    ours = live | {a for a, c in registry._aliases.items() if c in live}
    by = defaultdict(list)
    for c in corpora:
        by[c["path"].split("/")[0]].append(c)
    out = {}
    held = set()   # live-adapter jurisdictions whose law the record also holds (past versions exist there)
    for slug, cs in sorted(by.items()):
        code = next((c["code"][:2].lower() for c in cs if c.get("code")), "")
        if code in live and slug in with_text and any("/caselaw" not in c["path"] and c.get("history") != "metadata-only" for c in cs):
            held.add(code)
        if not code or code in ours or slug not in with_text:
            continue
        laws = [c for c in cs if "/caselaw" not in c["path"] and c.get("history") != "metadata-only"]
        if not laws:
            continue
        national = [c for c in laws if c["path"].split("/")[1] in ("national", "federal", "bund")] or laws[:1]
        # the corpus name is the country's, or a description of what the record holds
        given = national[0].get("name") or ""
        plain = len(given) <= 40 and ":" not in given and not re.search(r"\blaws?\b|^Testi", given, re.I)
        name = given if plain else slug.replace("-", " ").title()
        sub = len(laws) - len(national)
        cover = "; ".join(c.get("coverage", "").strip() for c in national if c.get("coverage"))
        # Lexifina's "N acts, M dated versions" can be far below what a search finds (Lithuania says
        # 1 act, search lists 12+), so only the dates are kept.
        cover = re.sub(r"\b\d[\d,]* acts, \d[\d,]* dated versions( from \d{4}-\d\d-\d\d to \d{4}-\d\d-\d\d)",
                       r"changes in force\1 (the latest change it holds; answers say when it was last checked)", cover)
        if not plain and given:
            cover = f"{given}: {cover}"
        out[code] = {
            "slug": slug,
            "name": name,
            "publishers": sorted({c.get("publisher", "") for c in national if c.get("publisher")}),
            "coverage": cover + (f"; plus {sub} state, provincial or local bodies of law" if sub else ""),
            "caselaw": any("/caselaw" in c["path"] for c in cs),
        }
    OUT.write_text('"""Generated by scripts/lexifina_countries.py from Lexifina\'s manifest; do not edit."""\n\n'
                   f"COUNTRIES = {pprint.pformat(out, width=110, sort_dicts=True)}\n\n"
                   "# Live-adapter jurisdictions the record also holds: get_law_on_date reads past versions there.\n"
                   f"LIVE_IN_RECORD = {sorted(held)!r}\n")
    print(f"wrote {len(out)} countries to {OUT.relative_to(ROOT)}; with case law: "
          f"{[k for k, v in out.items() if v['caselaw']]}")


if __name__ == "__main__":
    main()
